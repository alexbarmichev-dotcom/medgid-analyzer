export const formatNum = (n: number) =>
  (Math.round(n * 100) / 100).toString().replace('.', ',');

export const parseNum = (s: string) => parseFloat(s.replace(',', '.'));

export const convert = (x: UnitIndicator, value: number, reverse: boolean) => {
  if (x.mode === 'hba1c') return reverse ? value / 10.929 + 2.15 : (value - 2.15) * 10.929;
  if (x.mode === 'mul') return reverse ? value / x.k : value * x.k;
  return reverse ? value * x.k : value / x.k;
};

export const formulaText = (x: UnitIndicator, reverse: boolean) => {
  if (x.mode === 'hba1c')
    return reverse ? 'Формула: ммоль/моль ÷ 10,929 + 2,15' : 'Формула: (% − 2,15) × 10,929';
  return `Коэффициент: ${String(x.k).replace('.', ',')}`;
};

