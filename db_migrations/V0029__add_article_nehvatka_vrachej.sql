Прогноз неоптимистичный, но не безнадёжный. Если ничего не менять, ВОЗ ждёт дефицит в 11,1 миллиона к 2030 году. Выход на пенсию четверти врачей в ближайшие десять лет заставит страны либо нанимать иностранцев, либо перестраивать работу. Подготовка врачей растянута на годы, так что эффект сегодняшних решений мы увидим не раньше, чем через десятилетие.

## При чём здесь нейромедицина

Нейромедицина не заменит 23 тысячи врачей, но она может вернуть врачам часть времени.

Самый изученный пример это ИИ-«писарь»: программа слушает приём и составляет запись в карте. В исследовании Йеля выгорание у врачей снизилось с 51,9 до 38,8 процента за 30 дней использования. В Mass General Brigham доля выгоревших упала с 52,6 до 30,7 процента. Но с экономией времени всё скромнее. В одном исследовании ИИ-писарь сократил время работы с картой на 8,5 процента, это 2,4 минуты за приём. А в работе по неотложной помощи, опубликованной в июне 2026 года, ИИ сократил время на заметку на 1,6 минуты против 3,3 у человека-помощника, и ни тот, ни другой не увеличили часовую производительность врача.

Вывод трезвый: ИИ снимает бумажную нагрузку и помогает не выгорать, но дефицит рук это не лечит. И правильно: врач не должен превращаться в конвейер, а должен остаться человеком, который смотрит на вас, а не в экран.

Есть и вторая сторона, которую часто забывают: пациент. Если у врача десять минут, то подготовленный пациент получает больше. Расшифровка анализов на понятном языке, список вопросов, история результатов: всё это не отнимает у врача работу, а делает короткий приём осмысленнее.

