## Парадокс: врачей стало больше, а не хватает

Звучит странно, но это так. С 2006 по 2025 год плотность медработников в мире выросла на 52 процента, с 44,8 до 67,9 человека на 10 тысяч населения. Прогресс есть. Беда в том, что потребность росла ещё быстрее, а распределение осталось кривым: в Европе врачей на душу населения в 13 раз больше, чем в Африке. Нехватка врачей это не про пустую страну, а про пустое место в конкретном кабинете.

И есть совсем ироничный поворот. ВОЗ признаёт, что в некоторых странах безработные медики соседствуют с огромной неудовлетворённой потребностью в них, потому что у государства нет денег их нанять. Врач нужен, врач есть, а ставки нет.

## Когда это началось

Конкретной даты нет, и это важно понимать. Нехватка накапливалась десятилетиями. В 2016 году ВОЗ в глобальной стратегии оценивала будущий дефицит в 18 миллионов работников здравоохранения к 2030 году. Потом оценку уточнили: в 2022 году прогноз был 10 миллионов, а сегодня его подняли до 11,1. Цифра уменьшилась с 18 до 10, но снова выросла. Это не катастрофа с датой, а тренд с ускорением.

Пандемия тоже оставила след. В России, по данным министра здравоохранения, в 2020 году численность врачей упала с 557 до 541 тысячи, а к 2023 году вернулась почти к 558 тысячам. Министр объяснял это тем, что многие врачи старшего возраста ушли из отрасли после начала пандемии.

## Почему не хватает: четыре причины

1. Врача нельзя вырастить быстро. Замена опытного специалиста требует многих лет обучения и практики. Указ можно подписать за день, а врача за день не получить.

2. Стареют и врачи, и пациенты. В ВОЗ называют старение скрытым кризисом рабочей силы в здравоохранении. Пациентов с хроническими болезнями становится больше, врачей, готовых их вести, всё меньше.

3. Неравномерность. Люди едут туда, где зарплата и условия выше, а не туда, где нужнее. Плюс миграция: ВОЗ предупреждает, что она может усугублять нехватку в бедных странах.

4. Нагрузка и выгорание. Врачи берут по две-три ставки: многие совмещают работу в двух-трёх клиниках. Выгоревший врач уходит, и дефицит растёт.

