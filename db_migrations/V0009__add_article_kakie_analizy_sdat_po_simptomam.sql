## Когда не откладывать визит

Идите к врачу срочно, не дожидаясь анализов, если есть боль в груди, сильная одышка, обмороки, чёрный стул или кровь в стуле, желтуха, внезапная сильная слабость, высокая температура или резкая потеря веса без причины.

