## Десять частых вопросов о симптомах

### Какие анализы сдать при усталости и слабости?

Коротко: общий анализ крови, ферритин, ТТГ, глюкозу, витамин D, витамин B12, при необходимости СРБ и биохимию.

Усталость — симптом хитрый: за ней может скрываться что угодно, от недосыпа до щитовидной железы. Поэтому и список длинный. Стандартный минимум включает общий анализ крови, биохимию (глюкоза, функция печени и почек), ферритин, ТТГ, витамин D, витамин B12 и С-реактивный белок. Общий анализ покажет, нет ли анемии, ферритин расскажет о запасах железа, ТТГ о щитовидной железе, а глюкоза о том, не расшалился ли сахар. Если все цифры в порядке, врач станет искать причину дальше: сон, нагрузки, настроение.

### Какие анализы сдать при выпадении волос?

Коротко: ферритин, общий анализ крови, ТТГ, витамин D и B12.

Волосы первыми «жалуются» на недостаток железа и неполадки щитовидной железы. Если выпадение беспокоит, врачи часто смотрят ферритин, общий анализ крови, витамин D, B12 и ТТГ. Заодно стоит вспомнить, что на волосы влияют диета, стресс, недавние болезни и лекарства, поэтому после анализов обычно идёт осмотр у специалиста, трихолога или дерматолога. Не торопитесь покупать витамины «для волос» без анализов: без цифр вы лечите то, чего можете не иметь.

### Какие анализы показывают воспаление в организме?

Коротко: С-реактивный белок (СРБ), СОЭ, общий анализ крови с лейкоцитами. Иногда фибриноген и ферритин, но их читают осторожно.

СРБ называют одним из самых чувствительных показателей повреждения тканей при воспалении, некрозе и травме. СОЭ повышается потому, что при воспалении растут фибриноген и иммуноглобулины, они склеивают эритроциты в крупные столбики, которые оседают быстрее. Разница в скорости тоже есть: СОЭ измеряется около часа и в большинстве лабораторий уступает СРБ в быстроте.

Ферритин здесь особый персонаж. Это показатель запасов железа, но он ещё и белок острой фазы: воспаление может повышать его уровень, поэтому при воспалении нормальный ферритин ещё не доказывает, что железа достаточно. Врач учитывает это при чтении бланка.

Одна оговорка: повышенные маркёры воспаления говорят «что-то происходит», но не «что именно». Диагноз ставят по совокупности данных.

### Какие анализы сдать при подозрении на анемию?

Коротко: общий анализ крови (гемоглобин, эритроциты, индексы), ферритин, при необходимости железо с насыщением трансферрина, B12, фолат.

При анемии важно не только узнать, что гемоглобин снижен, но и выяснить причину. Расширенный профиль обычно включает гемограмму, витамин B12, ретикулоциты, насыщение железом, фолиевую кислоту и ферритин. Ферритин при этом называют главным показателем запасов железа в тканевых депо и ключевым маркёром скрытого дефицита. Такой набор позволяет различить железодефицитную, B12-дефицитную и фолиеводефицитную анемию.

Не забудьте про подготовку: анализы лучше сдавать утром натощак после 8–12 часов ночного голодания, а препараты железа, по согласованию с врачом, отменяют за 5–7 дней, иначе результат исказится. Принимали витамины? Обязательно скажите об этом.

### Какие анализы нужны при проблемах с щитовидной железой?

Коротко: ТТГ, свободный Т4, антитела к ТПО. Остальное по показаниям.

ТТГ — это гормон гипофиза, который управляет щитовидной железой, и потому чаще всего с него начинают: он первым реагирует на неполадки. Дальше врач обычно добавляет свободный Т4 (и по необходимости свободный Т3) и антитела к тиреоидной пероксидазе, чтобы выяснить, нет ли аутоиммунного процесса. УЗИ железы — это отдельная история, не из крови.

Две практические подсказки. Сообщите врачу обо всех препаратах и добавках: некоторые влияют на результат. И помните, что у беременных нормы ТТГ другие: исследователи специально определяют референсные интервалы ТТГ отдельно для каждого триместра. Сравнивать с «обычной» нормой в этом случае нельзя.

### Какие анализы сдать при болях в суставах?

Коротко: общий анализ крови, СРБ, СОЭ, мочевая кислота. Ревматоидный фактор, анти-ЦЦП и другие тесты назначает ревматолог по показаниям.

Анализы здесь работают как свидетели, а не как следователи. СРБ и СОЭ подскажут, есть ли воспаление, мочевая кислота нужна, когда подозревают подагру, а более специфические тесты на ревматоидный артрит и другие аутоиммунные состояния врач выбирает по картине: где болит, как долго, есть ли утренняя скованность. Нередко решающими оказываются не анализы, а осмотр и визуализация (рентген, УЗИ). Если сустав внезапно распух, покраснел и стал горячим, не ждите анализов, идите к врачу в тот же день.

### Какие анализы показывают проблемы с печенью?

Коротко: АЛТ, АСТ, ГГТ, щёлочная фосфатаза, билирубин (общий и прямой), альбумин и общий белок.

Это основа печёночной панели в биохимии. АЛТ и АСТ, ферменты клеток печени, повышаются при их повреждении, ГГТ и щёлочная фосфатаза «следят» за желчными путями, билирубин отражает обмен пигмента и работу печени, а альбумин показывает, как печень справляется с производством белка. Врач может добавить анализы на вирусные гепатиты и УЗИ.

Одно практическое замечание: небольшие колебания ферментов нередко связаны с алкоголем, лекарствами и тяжёлыми тренировками накануне, поэтому перед анализом их лучше исключить, а повышение стоит перепроверять. И не пугайтесь, если АЛТ чуть выше нормы: врач оценит это в контексте.

### Какие анализы сдать при частых простудах и слабом иммунитете?

Коротко: общий анализ крови с лейкоцитарной формулой, ферритин, глюкоза, витамин D. Иммунограмму назначает иммунолог, а не каждому.

Профессору, который двадцать лет читал лекции в промозглых аудиториях, вопрос знаком. Начинать стоит с базового: общий анализ крови покажет, нет ли анемии и сдвигов в лейкоцитах, ферритин и витамин D выявят частые дефициты, глюкоза исключит диабет, который тоже располагает к инфекциям. Расширенные тесты иммунной системы обычно уместны только по рекомендации врача и при действительно затяжных или тяжёлых инфекциях. Не торопитесь платить за «иммунограмму на всякий случай».

### Какие анализы сдать при проблемах с кожей и акне?

Коротко: чаще всего анализы не нужны. При упорном акне или признаках гормональных нарушений врач может назначить половые гормоны (тестостерон, ДГЭА-С), ЛГ и ФСГ, пролактин, ТТГ и глюкозу.

Это один из случаев, где скромность врача оправдана: обычное подростковое акне в большинстве случаев не требует анализов крови. Но если акне у женщины сочетается с нерегулярным циклом, избыточным ростом волос и ростом массы тела, дерматолог или гинеколог могут проверить гормоны. Знаете ли вы, что гормональные анализы у женщин сдают строго по дням цикла? Узнайте у лаборатории, на какой день записываться, а то результат окажется бесполезным.

### Какие анализы сдать при нарушении сна?

Коротко: анализа, который ставит диагноз «бессонница», нет. Врач может исключить причины: ТТГ, общий анализ крови и ферритин, глюкозу.

Тут профессор обязан быть честным: сон изучают с помощью беседы, дневника сна, а иногда специальных исследований (полисомнография), а не кровью. Анализы нужны, чтобы исключить то, что мешает спать: щитовидную железу, анемию или дефицит железа (он нередко связан с беспокойными ногами), нарушения сахара. Если вас будят остановки дыхания и дневная сонливость, нужен врач-сомнолог, а не очередной витамин.

