## Частые вопросы

### Что такое персональная медицина?

Подход, при котором решения о профилактике и лечении принимаются на основе данных конкретного человека и их изменений во времени, а не только средних значений по популяции.

### Может ли ИИ расшифровать анализ крови?

Да, в части перевода и объяснения: распознать показатели, пересчитать единицы, объяснить, что измеряет каждый параметр, показать динамику. Диагноз и назначение остаются за врачом.

### Чем полезна динамика показателей, если значения в норме?

Норма — широкий интервал. Показатель, который вырос вдвое, оставаясь внутри референса, заслуживает внимания и вопроса врачу.

### Почему референсы в разных лабораториях отличаются?

Интервалы зависят от метода исследования, оборудования и реактивов. Норму на бланке нельзя механически переносить на результат из другой лаборатории.

