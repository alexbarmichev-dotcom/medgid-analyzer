## Почему персонализация начинается с единиц измерения

Практическая проблема, о которой редко говорят: один и тот же показатель в разных странах и лабораториях записывают по-разному. Глюкоза в ммоль/л и мг/дл, гемоглобин в г/л и г/дл, гормоны в совершенно несопоставимых единицах.

Из-за этого человек, переехавший в другую страну, теряет ориентиры. Бланк из клиники, например, в Нячанге и бланк из Москвы описывают одно и то же тело, но выглядят как два разных языка. Первый шаг персонализации — привести данные к одному виду, чтобы их вообще можно было сравнить.

Второй шаг — учитывать, что референсные интервалы задаёт лаборатория. Норма, напечатанная на вашем бланке, относится к методу и оборудованию этой лаборатории. Сравнивать показатель с нормой из интернета — распространённая и довольно бессмысленная привычка.

