## Как подготовиться к приёму, чтобы 15 минут работали на вас

Пока робот учится писать, у вас есть собственные способы вернуть врачу глаза:

1. Запишите симптомы заранее: что, когда началось, что усиливает или облегчает.

2. Составьте список вопросов, а не «посмотрите, что у меня».

3. Возьмите с собой бланки анализов вместе с референсами лаборатории и историю прошлых результатов.

4. Выпишите принимаемые лекарства и добавки.

5. Скажите главное в первые минуты: это то, ради чего вы пришли.

