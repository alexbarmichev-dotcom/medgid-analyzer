## Что такое ИИ-писарь

ИИ-писарь, или «амбиентный» писарь, это система, которая слушает и расшифровывает разговор врача с пациентом, составляет запись о визите и заполняет обязательную документацию. Врач после приёма проверяет и подписывает текст. Идея простая: вместо того чтобы печатать, врач смотрит на пациента.

## Почему врач «пишет, а не смотрит»

Дело в нормативах и бумагах. Время приёма у терапевта и педиатра сегодня укладывается примерно в 15 минут (раньше ориентировались на 12). Минздрав сам оценил долю документации: для многих специалистов она не должна превышать 35 процентов времени приёма, хотя, как отмечают главные врачи, такой документ носит рекомендательный характер. Реальность суровее: по оценке Счётной палаты, на задачи, не связанные с лечением, уходит до половины рабочего времени, в зависимости от региона. Одна из практикующих терапевтов сравнивает объём ежедневных бумаг с написанием небольшой научной статьи.

Попытки сократить бумаги были и раньше: в 2014 году Минздрав обещал из девяти документов, за которые отвечает врач, оставить только три. Бумаг по-прежнему много, поэтому тема ИИ-помощника попала в точку.

