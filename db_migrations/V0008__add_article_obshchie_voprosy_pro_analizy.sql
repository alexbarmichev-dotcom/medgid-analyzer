## Десять вопросов про анализы

### Какие анализы нужно сдавать раз в год для профилактики?

Коротко: общий анализ крови, глюкозу, холестерин (липидный профиль) и общий анализ мочи. Остальное, например, ТТГ, АЛТ и АСТ, креатинин, гликированный гемоглобин, добавляет врач по возрасту и показаниям.

В обзорах для взрослых базовый набор такой: общий анализ крови, общий анализ мочи и биохимия с глюкозой натощак и холестерином или липидным спектром. Расширенный чекап часто включает общий анализ крови и мочи, глюкозу или HbA1c, липидограмму, АЛТ и АСТ, креатинин, ТТГ, а мужчинам после 45 лет ещё ПСА. Но тот же источник честно оговаривается: список ежегодных анализов должен определять врач с учётом особенностей пациента. В диспансеризации для россиян всё чётко: до 39 лет раз в три года, с 40 лет ежегодно, холестерин и глюкозу определяют с 18 лет раз в год, а общий анализ крови с 40 лет раз в год. Если вам 25 и вы чувствуете себя прекрасно, это не причина откладывать глюкозу и холестерин до пенсии.

### Как подготовиться к сдаче анализов крови?

Коротко: прийти утром натощак, накануне не есть жирное и не пить алкоголь, не нагружать себя спортом, не курить перед забором, а главное, успокоиться.

Типичные правила лабораторий такие:

• Время: с 8 до 11 часов утра, между последним приёмом пищи и забором должно пройти не менее 8 часов, воду можно пить в обычном режиме.

• Накануне: за 1–2 дня исключить жирную пищу и алкоголь, последний приём пищи не позднее 19:00.

• Нагрузки и нервы: перед сдачей снизить физические нагрузки, исключить баню и сауну, успокоиться, чтобы не вызвать лишний выброс гормонов.

• Курение: воздержаться за 1–2 часа до забора.

• После процедур: кровь на анализы нельзя сдавать после физиотерапии, рентгена и других инструментальных исследований.

Просто потому, что результат зависит от того, в каком состоянии вы пришли, а не только от того, что у вас внутри. Повторять анализы лучше в тех же условиях, что и первый раз, в то же время суток. Иначе сравнивать будет нечего.

### Можно ли сдавать анализы во время месячных?

Коротко: большинство анализов можно, но для некоторых день цикла имеет значение. Общий анализ крови лучше сдавать не в первые дни, а гормоны строго по дням цикла.

Общий анализ крови можно сдавать и во время месячных, но точнее результат по гемоглобину, эритроцитам и лейкоцитам получается в середине или конце цикла. А вот с гормонами интереснее: ФСГ, ЛГ и эстрадиол сдают на 2–5 день цикла, а прогестерон во второй фазе, на 21–23 день при 28-дневном цикле. Тиреоидные гормоны в большинстве случаев можно проверять и во время месячных. Общий анализ мочи многие лаборатории не рекомендуют сдавать во время менструации. Рекомендации у разных лабораторий отличаются (например, по пролактину одни пишут «в любой день», другие «кроме дней менструации»), поэтому порядок такой: узнайте требования лаборатории, а не доверяйте общей схеме.

### Через сколько после еды можно сдавать кровь?

Коротко: обычно через 8–14 часов. Для биохимии чаще 12–14, для глюкозы 10–14.

Лаборатории называют разные цифры: не менее 8 часов, 12–14 часов для биохимии, гормонов и маркёров инфекций и 10–14 часов ночного голодания для глюкозы. Попадать в середину этой вилки удобно: поужинали в 19:00, сдали кровь в 8–9 утра. Для некоторых гормонов врач может разрешить сдачу через 4–5 часов после еды, но это по назначению.

Если вам хочется «просто выпить воды», воду можно. Всё остальное, от сока до жвачки, лучше оставить на потом.

### Почему нельзя пить кофе перед анализами?

Коротко: потому что кофе — это тоже еда и ещё и стимулятор. Он меняет сахар, гормоны и другие показатели.

В инструкциях лабораторий сказано прямо: кофе, чай и сок — это тоже еда, можно пить только воду, а для анализа на глюкозу даже несладкий утренний кофе запрещён, поскольку чашка кофе кардинально изменит показатели глюкозы. Объясняют это так: кофеин блокирует аденозиновые рецепторы, что приводит к выбросу адреналина и норадреналина, и растёт уровень кортизола, влияющий на гормональные анализы. Для большинства анализов крови кофе остаётся под запретом как минимум за 8–12 часов до процедуры. Я знаю, что для многих это звучит как личное оскорбление. Но кофе от вас никуда не уйдёт: подождите до забора, а потом заслуженный латте.

### Как часто нужно сдавать общий анализ крови?

Коротко: здоровому человеку примерно раз в год, а при хронических болезнях или назначениях чаще, как скажет врач.

В профилактических схемах общий анализ крови рекомендуют сдавать ежегодно всем взрослым, а в диспансеризации он предусмотрен с 40 лет раз в год. Он нужен, чтобы вовремя заметить анемию, воспаление и другие системные нарушения. Чаще сдают при болезнях, приёме лекарств или наблюдении, и тут график определяет врач.

### Что показывает биохимический анализ крови?

Коротко: работу внутренних органов и обмен веществ: печень, почки, поджелудочную, уровень сахара, холестерина, белков, ферментов и минералов.

Биохимия оценивает функцию печени, почек и поджелудочной железы, уровень холестерина и глюкозы. Помимо этого, она смотрит на ферменты (АЛТ, АСТ, ГГТ), билирубин, белки, мочевину, креатинин, электролиты (калий, натрий, хлориды) и кальций. Один показатель редко говорит сам за себя, поэтому врач читает их в связке.

### В чём разница между общим и биохимическим анализом крови?

Коротко: общий анализ смотрит на клетки крови, биохимия на то, что растворено в плазме и сыворотке и как работают органы.

Общий анализ крови оценивает количество и качество форменных элементов крови и помогает выявить воспаление, анемию и инфекции. Биохимия, напротив, показывает химический состав и работу органов.

| Сравнение | Общий анализ крови | Биохимический анализ крови
| Что смотрит | клетки: эритроциты, лейкоциты, тромбоциты, гемоглобин | вещества в плазме: глюкоза, холестерин, ферменты, белки, электролиты
| Что помогает увидеть | анемию, воспаление, инфекцию | работу печени, почек, обмен веществ
| Как сдают | утром, правила зависят от лаборатории | утром строго натощак, обычно 8–14 часов голода

### Какие анализы сдают натощак, а какие нет?

Коротко: большинство анализов крови натощак, особенно биохимия, липиды, глюкоза и гормоны. Для общего анализа правила разные, смотрите требования вашей лаборатории.

Одна лаборатория пишет, что биохимию, гормоны и маркёры инфекций нужно сдавать натощак, не менее 12–14 часов после последнего приёма пищи. Другие допускают для общего анализа утренние часы натощак или спустя 4–5 часов после последнего приёма пищи. Гормональные исследования сдают натощак в утреннее время, а по назначению врача можно спустя 4–5 часов после еды. Поэтому единого ответа нет, и самый надёжный способ — уточнить правило в вашей лаборатории при записи.

### Можно ли сдавать анализы при простуде?

Коротко: плановые профилактические анализы лучше отложить до выздоровления. Если врач назначил анализ из-за болезни, сдавать нужно.

При обычном ОРВИ в первые три-пять дней лабораторная диагностика чаще всего не нужна, а при риске осложнений врач может назначить общий анализ крови с лейкоцитарной формулой и анализ на С-реактивный белок. Для плановых исследований, например, иммунного статуса, не рекомендуется сдавать их во время ОРВИ. Логика простая: во время болезни показатели меняются из-за самой болезни, и профилактическая картина получается искажённой. Когда самочувствие вернётся, можно сдавать плановые анализы. Если сомневаетесь, спросите врача, он знает, что именно с вами происходит.

