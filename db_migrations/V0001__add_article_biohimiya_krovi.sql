## История: от колбы до автоанализатора

### Моча как первый «анализ»

Первые записи об уроскопии, осмотре мочи, относят к четвёртому тысячелетию до нашей эры, а Гиппократ считал мочу фильтратом жидкостей организма. Врач разглядывал её в стеклянной колбе, которая стала символом врачебной учёности.

### Сахар на вкус, на муравьёв и на реактив

Идея измерять сахар старше глюкометров: раньше «глюкометрами» служили муравьи, мухи, а иногда и собственные вкусовые ощущения врача. Затем появились химические тесты, и исследователи перешли от мочи к крови, потому что она давала более точный результат.

### Конвейер для проб

Американский биохимик Леонард Скеггс предложил прибор, где пробы шли по трубкам непрерывным потоком. В 1957 году вышел AutoAnalyzer, и за десять лет число лабораторных тестов выросло примерно в сто раз.

### Появилась «норма»

До 1960-х лаборатории нередко работали по отдельности, и каждая задавала свои пределы нормы. В 1969 году Грасбек и Сарис предложили считать нормой центральные 95 процентов результатов здоровых людей. Из этого следует, что пять процентов здоровых людей по определению оказываются за пределами нормы, и именно поэтому отдельная «лишняя» строчка в бланке не всегда повод для тревоги.

## Как делают биохимию сегодня

Кровь берут из вены, отделяют сыворотку и измеряют показатели на автоанализаторах: большинство определяют на одном приборе за один заход. Для части показателей лаборатории используют разные методы, например, для кальция существуют и фотометрия, и масс-спектрометрия. Поэтому референсы одного и того же показателя в разных лабораториях могут отличаться.

